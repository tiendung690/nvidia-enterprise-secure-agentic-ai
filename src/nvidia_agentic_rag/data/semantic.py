from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

CustomerDataset = Literal["gold_customer_order_summary"]
BookDataset = Literal["gold_book_sales_summary"]
AnalyticsDataset = Literal[
    "gold_customer_order_summary",
    "gold_book_sales_summary",
    "cross_gold",
]
AnalyticsOperation = Literal[
    "lookup",
    "rank",
    "reconcile",
    "customer_and_top_book",
    "compare_customer_top_book",
    "top_book_causal_guard",
    "unsupported",
]
UnsupportedReason = Literal[
    "time_dimension_not_available",
    "causality_not_available",
    "customer_book_relation_not_available",
    "customer_book_metric_not_available",
]
SortDirection = Literal["ASC", "DESC"]


@dataclass(frozen=True)
class MetricDefinition:
    name: str
    field: str | None
    grain: str
    additive: bool
    formula_id: str | None = None
    formula: str | None = None
    inputs: tuple[str, ...] = ()
    compatible_with: tuple[str, ...] = ()
    aggregation_semantics: str = "sum"
    warning: str | None = None


@dataclass(frozen=True)
class DatasetDefinition:
    name: str
    grain: str
    entity_key: str
    metrics: dict[str, MetricDefinition]


class AnalyticsQueryPlan(BaseModel):
    """Strict analytics DSL. The model can choose a capability, never an arbitrary formula/SQL."""

    model_config = ConfigDict(extra="forbid")

    dataset: AnalyticsDataset
    operation: AnalyticsOperation
    entity_id: str | None = Field(default=None, max_length=128)
    sort_metric: str | None = Field(default=None, max_length=128)
    direction: SortDirection = "DESC"
    limit: int = Field(default=5, ge=1, le=100)
    derived_metrics: list[str] = Field(default_factory=list, max_length=8)
    unsupported_reason: UnsupportedReason | None = None

    @model_validator(mode="after")
    def validate_shape(self) -> "AnalyticsQueryPlan":
        if self.operation == "lookup" and not self.entity_id:
            raise ValueError("lookup requires entity_id")
        if (
            self.operation in {"customer_and_top_book", "compare_customer_top_book"}
            and not self.entity_id
        ):
            raise ValueError(f"{self.operation} requires customer entity_id")
        if self.operation == "rank" and not self.sort_metric:
            raise ValueError("rank requires sort_metric")
        if self.operation == "reconcile" and self.dataset != "cross_gold":
            raise ValueError("reconcile requires dataset='cross_gold'")
        if self.operation == "unsupported" and not self.unsupported_reason:
            raise ValueError("unsupported operation requires unsupported_reason")
        return self


class SemanticMetricRegistry:
    """Application-owned business semantics for the curated gold serving layer.

    This registry is intentionally code/config owned. It is not generated by the LLM and is the
    only place where derived formulas and cross-grain compatibility are defined.
    """

    version = "semantic-registry-v2"

    def __init__(self) -> None:
        customer_metrics = {
            "total_amount": MetricDefinition(
                name="total_amount",
                field="total_amount",
                grain="customer",
                additive=True,
                compatible_with=("total_revenue",),
            ),
            "total_quantity": MetricDefinition(
                name="total_quantity",
                field="total_quantity",
                grain="customer",
                additive=True,
                compatible_with=("total_quantity",),
            ),
            "total_orders": MetricDefinition(
                name="total_orders",
                field="total_orders",
                grain="customer",
                additive=False,
                aggregation_semantics="distinct_count",
                warning="unsafe_to_sum_across_book_dimension",
            ),
            "average_spending_per_order": MetricDefinition(
                name="average_spending_per_order",
                field=None,
                grain="customer",
                additive=False,
                formula_id="customer.average_spending_per_order.v1",
                formula="total_amount / total_orders",
                inputs=("total_amount", "total_orders"),
            ),
            "average_units_per_order": MetricDefinition(
                name="average_units_per_order",
                field=None,
                grain="customer",
                additive=False,
                formula_id="customer.average_units_per_order.v1",
                formula="total_quantity / total_orders",
                inputs=("total_quantity", "total_orders"),
            ),
        }
        book_metrics = {
            "total_revenue": MetricDefinition(
                name="total_revenue",
                field="total_revenue",
                grain="book",
                additive=True,
                compatible_with=("total_amount",),
            ),
            "total_quantity": MetricDefinition(
                name="total_quantity",
                field="total_quantity",
                grain="book",
                additive=True,
                compatible_with=("total_quantity",),
            ),
            "total_orders": MetricDefinition(
                name="total_orders",
                field="total_orders",
                grain="book",
                additive=False,
                aggregation_semantics="distinct_count",
                warning="unsafe_to_sum_across_book_dimension",
            ),
            "revenue_per_unit": MetricDefinition(
                name="revenue_per_unit",
                field=None,
                grain="book",
                additive=False,
                formula_id="book.revenue_per_unit.v1",
                formula="total_revenue / total_quantity",
                inputs=("total_revenue", "total_quantity"),
            ),
            "average_units_per_order": MetricDefinition(
                name="average_units_per_order",
                field=None,
                grain="book",
                additive=False,
                formula_id="book.average_units_per_order.v1",
                formula="total_quantity / total_orders",
                inputs=("total_quantity", "total_orders"),
            ),
        }
        self.datasets: dict[str, DatasetDefinition] = {
            "gold_customer_order_summary": DatasetDefinition(
                name="gold_customer_order_summary",
                grain="one row per customer",
                entity_key="customer_id",
                metrics=customer_metrics,
            ),
            "gold_book_sales_summary": DatasetDefinition(
                name="gold_book_sales_summary",
                grain="one row per book",
                entity_key="book_id",
                metrics=book_metrics,
            ),
        }

    def dataset(self, name: str) -> DatasetDefinition:
        try:
            return self.datasets[name]
        except KeyError as exc:
            raise ValueError(f"Unsupported analytics dataset: {name}") from exc

    def metric(self, dataset: str, name: str) -> MetricDefinition:
        definition = self.dataset(dataset)
        try:
            return definition.metrics[name]
        except KeyError as exc:
            raise ValueError(f"Unsupported metric '{name}' for dataset '{dataset}'") from exc

    def validate_plan(self, plan: AnalyticsQueryPlan, *, max_rows: int) -> AnalyticsQueryPlan:
        if plan.operation == "unsupported":
            return plan.model_copy(update={"limit": min(plan.limit, max_rows)})
        if plan.dataset != "cross_gold":
            definition = self.dataset(plan.dataset)
            if plan.sort_metric:
                metric = self.metric(plan.dataset, plan.sort_metric)
                if metric.field is None:
                    raise ValueError("Ranking by derived metrics is not enabled in this version")
            for metric_name in plan.derived_metrics:
                metric = self.metric(plan.dataset, metric_name)
                if metric.formula_id is None:
                    raise ValueError(
                        f"'{metric_name}' is a source metric, not an allowlisted derived metric"
                    )
            if plan.operation == "lookup" and not definition.entity_key:
                raise ValueError("Dataset does not support entity lookup")
        return plan.model_copy(update={"limit": min(plan.limit, max_rows)})

    def semantic_snapshot(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "capabilities": {
                "time_dimension": {
                    "available": False,
                    "reason": (
                        "Gold serving summaries expose current snapshots, not a governed "
                        "time series."
                    ),
                },
                "causal_evidence": {
                    "available": False,
                    "reason": (
                        "Gold aggregates are descriptive and do not establish causal mechanisms."
                    ),
                },
                "customer_book_grain": {
                    "available": False,
                    "reason": (
                        "No governed customer-to-book/order-item relation is exposed by the "
                        "current Gold serving contract."
                    ),
                },
            },
            "datasets": {
                name: {
                    "grain": dataset.grain,
                    "entity_key": dataset.entity_key,
                    "metrics": {
                        metric_name: {
                            "additive": metric.additive,
                            "aggregation_semantics": metric.aggregation_semantics,
                            "compatible_with": list(metric.compatible_with),
                            "formula_id": metric.formula_id,
                            "formula": metric.formula,
                            "inputs": list(metric.inputs),
                            "warning": metric.warning,
                        }
                        for metric_name, metric in dataset.metrics.items()
                    },
                }
                for name, dataset in self.datasets.items()
            },
        }


